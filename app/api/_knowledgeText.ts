// "让 AI 整理格式后再保存"用到的提示词与状态标注。
//
// 企业知识和个人知识两个入口都要用，放在一处免得两边各写一份、日后改一处漏一处。
//
// 与"数据采集"里那份整理提示词是平行关系而非同一份：采集侧要按数据源配置的
// 输出格式（Markdown/表格/JSON/原始文本）组织，知识侧没有这个概念，只做可读性整理。
// 两边共有的底线是同一条——保留原始事实、不许编造，这也是整理功能唯一真正的风险点。

export const KNOWLEDGE_POLISH_INSTRUCTION = [
  "请把下面这段内容整理成结构清晰、可直接阅读的中文知识条目。要求：",
  "1. 只输出内容本身，不要输出整理说明、过程描述或对内容的评价；",
  "2. 必须保留原始事实、数字与专有名词，不得编造、补全或推测；",
  "3. 原文是表格或列表时，整理成 Markdown 表格或列表，并保留全部记录，不要抽样或省略；",
  "4. 原文本身已经清晰时，只做分段和标题整理，不要强行改写措辞。",
].join("\n");

/** 整理过的内容要在来源标注里留痕，否则事后无法区分哪些是原文、哪些被模型动过。 */
export function markPolished(sourceType: string, state: "done" | "failed" | "off") {
  if (state === "off") return sourceType;
  return state === "done" ? `${sourceType} · AI整理` : `${sourceType} · AI整理失败，已保留原文`;
}
